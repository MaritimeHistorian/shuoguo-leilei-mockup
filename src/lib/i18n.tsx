type TranslationKey = keyof typeof translations.en

type I18nContextValue = {
  language: Language
  setLanguage: (language: Language) => void
  toggleLanguage: () => void
  t: (key: TranslationKey) => string
  localize: (text: LocalizedText) => string
  phrase: (text: string) => string
}

export const I18nContext = createContext<I18nContextValue | null>(null)

export function useI18n() {
  const value = useContext(I18nContext)

  if (!value) {
    throw new Error('useI18n must be used within an I18nContext provider')
  }

  return value
}

export function translateText(text: LocalizedText, language: Language) {
  return text[language]
}

export function translatePhrase(text: string, language: Language) {
  if (language === 'en') {
    return text
  }

  return phraseTranslations[text] ?? text
}

export function createI18nValue(
  language: Language,
  setLanguage: (language: Language) => void,
) {
  return {
    language,
    setLanguage,
    toggleLanguage: () => {
      setLanguage(language === 'en' ? 'zh' : 'en')
    },
    t: (key: TranslationKey) => translations[language][key],
    localize: (text: LocalizedText) => translateText(text, language),
    phrase: (text: string) => translatePhrase(text, language),
  }
}
